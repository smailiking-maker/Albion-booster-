package com.albionboost.app

data class ServerNode(
    val id: String,
    val countryCode: String,
    val country: String,
    val city: String,
    val region: String,
    val albionTarget: String,
    val probeHost: String,
    val probePort: Int = 443,
    val endpoint: String = "",
    val serverPublicKey: String = "",
    val clientPrivateKey: String = "",
    val presharedKey: String = "",
    val tunnelAddress: String = "10.66.66.2/32",
    val dnsServers: String = "1.1.1.1, 8.8.8.8",
    val mtu: Int = 1280,
    val keepaliveSeconds: Int = 25,
    val jc: Int? = null,
    val jmin: Int? = null,
    val jmax: Int? = null,
    val s1: Int? = null,
    val s2: Int? = null,
    val h1: Int? = null,
    val h2: Int? = null,
    val h3: Int? = null,
    val h4: Int? = null,
    val latencyMs: Int? = null
) {
    fun isConfigured(): Boolean {
        return endpoint.contains(":") &&
            !endpoint.startsWith("YOUR_") &&
            serverPublicKey.trim().length >= 43 &&
            clientPrivateKey.trim().length >= 43
    }

    fun effectiveProbeHost(): String {
        return if (endpoint.contains(":")) endpoint.substringBefore(":").trim() else probeHost
    }

    fun effectiveProbePort(): Int {
        return if (endpoint.contains(":")) {
            endpoint.substringAfter(":").trim().toIntOrNull() ?: probePort
        } else {
            probePort
        }
    }
}

